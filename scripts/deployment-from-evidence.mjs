// Points the web app at the contracts recorded in docs/evidence/<network>-run.json.
import { readFileSync, writeFileSync } from 'node:fs';
const net = process.argv[2] ?? 'preprod';
const r = JSON.parse(readFileSync(`docs/evidence/${net}-run.json`, 'utf8'));
const d = {
  network: net,
  contract: r.contractAddress,
  tkrwContract: r.tkrwContract,
  faceValue: r.finalShow.faceValue,
  showId: r.showId,
  explorer: 'https://explorer.preprod.midnight.network/contracts/',
};
writeFileSync(
  'app/src/deployment.ts',
  `// Which deployment the app reads. Generated by scripts/deployment-from-evidence.mjs.\nexport const DEPLOYMENT = ${JSON.stringify(d, null, 2)} as { network: 'local' | 'preprod'; contract: string; tkrwContract: string; faceValue: string; showId: string; explorer: string };\n`,
);
console.log(`app now reads ${net} contract ${d.contract}`);
